INSERT INTO bird_habitats (bird_id, habitat_id, is_primary)
SELECT b.bird_id, h.habitat_id, n.is_primary
FROM new_bird_habitats n
JOIN birds b    ON b.latin_name = n.latin_name
JOIN habitats h ON h.name = n.habitat_name;

DROP TEMPORARY TABLE new_bird_habitats;

-- Check: every bird should have exactly one primary habitat.
-- This should return 100 rows, all with primary_count = 1.
SELECT b.common_name, SUM(bh.is_primary) AS primary_count, COUNT(*) AS habitat_count
FROM birds b
JOIN bird_habitats bh ON bh.bird_id = b.bird_id
GROUP BY b.bird_id
ORDER BY primary_count, b.common_name;

