-- Day 11: Six habitat tiles to match the mockup
-- Woodlands, Grasslands, Backyard, Aquatic, Desert, Wetlands
--
-- What this script does:
--   1. Renames the 4 existing tiles and habitats, and adds Aquatic and Desert.
--   2. Rebuilds bird_habitats from the Habitat line of each bird in
--      "Future MySQL Bird Data.txt", using this mapping:
--        Forests and Woodlands               -> Woodlands
--        Fields, Meadows, and Grasslands     -> Grasslands
--        Shrublands, Savannas, and Thickets  -> Grasslands
--        Urban and Suburban Habitats         -> Backyard
--        Lakes, Ponds, and Rivers            -> Aquatic
--        Desert and Arid Habitats            -> Desert
--        Freshwater / Saltwater Wetlands     -> Wetlands
--      (Coasts, Arroyos and Canyons, High Mountains, Tundra, and Landfills
--       are left out because they don't fit one tile well in Utah.)
--   3. Keeps each bird's old primary habitat when it still applies.
--
-- Everything runs inside one transaction: if any line fails, nothing changes.

-- Workbench's "safe update mode" blocks DELETE without a WHERE.
-- We really do want to clear all of bird_habitats, so turn it off
-- for this script only (it's turned back on at the end).
SET SQL_SAFE_UPDATES = 0;

START TRANSACTION;

-- 1. Tiles: rename the existing four (same ids), then add two new ones.
--    tile_id stays fixed so BirdID.razor can refer to tiles by number.
UPDATE tiles SET name = 'Woodlands',  icon = 'images/icons/woods.svg',    description = 'Woods, mountain forests, and shrubby edges', sort_order = 1 WHERE tile_id = 1;
UPDATE tiles SET name = 'Grasslands', icon = 'images/icons/grass.svg',    description = 'Fields, meadows, and sagebrush',             sort_order = 2 WHERE tile_id = 2;
UPDATE tiles SET name = 'Wetlands',   icon = 'images/icons/reeds.svg',    description = 'Marshes and reedy edges',                    sort_order = 6 WHERE tile_id = 3;
UPDATE tiles SET name = 'Backyard',   icon = 'images/icons/backyard.svg', description = 'Backyards, parks, and feeders',              sort_order = 3 WHERE tile_id = 4;

INSERT INTO tiles (tile_id, name, icon, description, sort_order) VALUES
    (5, 'Aquatic', 'images/icons/lake.svg',   'Lakes, ponds, and rivers', 4),
    (6, 'Desert',  'images/icons/desert.svg', 'Dry, open desert country', 5);

-- 2. Habitats: one per tile, with the same name, so the Bird Profile
--    shows the same words the user picked on the Bird ID page.
UPDATE habitats SET name = 'Woodlands'  WHERE habitat_id = 1;
UPDATE habitats SET name = 'Grasslands' WHERE habitat_id = 2;
UPDATE habitats SET name = 'Wetlands'   WHERE habitat_id = 3;
UPDATE habitats SET name = 'Backyard'   WHERE habitat_id = 4;

INSERT INTO habitats (habitat_id, name, tile_id) VALUES
    (5, 'Aquatic', 5),
    (6, 'Desert',  6);

